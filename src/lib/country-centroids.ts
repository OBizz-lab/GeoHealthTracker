/**
 * Look up a country centroid by ISO 3166-1 alpha-2 code.
 * Returns `null` for "ZZ" / unknown / no-match.
 */
export function centroidFor(iso: string | null | undefined): [number, number] | null {
  if (!iso || iso === "ZZ") return null;
  return COUNTRY_CENTROIDS[iso.toUpperCase()] ?? null;
}
